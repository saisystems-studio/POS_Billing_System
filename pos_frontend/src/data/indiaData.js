// Derive unique sorted list of all states
export const INDIA_STATES = [...new Set(INDIA_DISTRICTS.map(d => d.state))].sort();

// Helper: given a district name, get its state and country
export function getStateAndCountryByDistrict(districtName) {
  const found = INDIA_DISTRICTS.find(
    d => d.district.toLowerCase() === districtName.toLowerCase()
  );
  return found ? { state: found.state, country: found.country } : null;
}

// Helper: given a state name, get districts in that state
export function getDistrictsByState(stateName) {
  return INDIA_DISTRICTS
    .filter(d => d.state === stateName)
    .map(d => d.district)
    .sort();
}
